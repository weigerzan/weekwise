const { contextBridge, ipcRenderer } = require('electron');
contextBridge.exposeInMainWorld('desktop', {
  read: () => ipcRenderer.invoke('tasks:read'),
  save: (state, previous) => ipcRenderer.invoke('tasks:save', state, previous),
  completeTask: (id, actualMinutes) => ipcRenderer.invoke('tasks:complete', id, actualMinutes),
  toggleTask: id => ipcRenderer.invoke('tasks:toggle', id),
  onState: callback => { const listener = (_event, state) => callback(state); ipcRenderer.on('tasks:changed', listener); return () => ipcRenderer.removeListener('tasks:changed', listener); },
  aiStatus: () => ipcRenderer.invoke('ai:status'),
  saveAIConfig: value => ipcRenderer.invoke('ai:config', value),
  planAI: (state, start, today) => ipcRenderer.invoke('ai:plan', state, start, today),
  planNatural: (state, description, startDate, today) => ipcRenderer.invoke('ai:natural', state, description, startDate, today),
  replanNatural: (state, description, referenceWeekStart, throughDate, today) => ipcRenderer.invoke('ai:replan', state, description, referenceWeekStart, throughDate, today),
  planDay: (state, description, date, today, currentTime) => ipcRenderer.invoke('ai:day', state, description, date, today, currentTime),
  cancelAI: () => ipcRenderer.invoke('ai:cancel'),
  openWidget: mode => ipcRenderer.invoke('widget:open', mode),
  setWidgetMode: mode => ipcRenderer.invoke('widget:mode', mode),
  resizeCompactWidget: height => ipcRenderer.invoke('widget:height', height),
  closeWidget: () => ipcRenderer.invoke('widget:close'),
  pinWidget: value => ipcRenderer.invoke('widget:pin', value),
  showMain: () => ipcRenderer.invoke('main:show'),
  reminderStatus: () => ipcRenderer.invoke('reminders:status'),
  testReminder: value => ipcRenderer.invoke('reminders:test', value),
  readAlarm: () => ipcRenderer.invoke('alarm:read'),
  dismissAlarm: () => ipcRenderer.invoke('alarm:dismiss'),
  onAlarm: callback => { const listener = (_event, value) => callback(value); ipcRenderer.on('alarm:changed', listener); return () => ipcRenderer.removeListener('alarm:changed', listener); },
  exportBackup: state => ipcRenderer.invoke('backup:export', state),
  importBackup: () => ipcRenderer.invoke('backup:import'),
});
